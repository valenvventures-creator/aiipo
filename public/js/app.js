// Progressive enhancement only - every page works without JavaScript except file upload and the guide.
(function () {
  'use strict';
  const csrfOf = (form) => form.querySelector('input[name="_csrf"]')?.value || '';

  document.addEventListener('change', (e) => {
    if (e.target.matches('select[data-autosubmit]')) e.target.form.submit();
  });

  document.addEventListener('click', (e) => {
    const t = e.target.closest('[data-toggle="sidebar"]');
    if (t) {
      const sb = document.getElementById('sidebar');
      const open = sb.classList.toggle('open');
      t.setAttribute('aria-expanded', String(open));
      return;
    }
    const c = e.target.closest('[data-confirm]');
    if (c && !window.confirm(c.getAttribute('data-confirm'))) e.preventDefault();
    const sb = document.getElementById('sidebar');
    if (sb && sb.classList.contains('open') && !e.target.closest('#sidebar')) sb.classList.remove('open');
  });

  function toBase64(buf) {
    const bytes = new Uint8Array(buf);
    let bin = '';
    for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode.apply(null, bytes.subarray(i, i + 0x8000));
    return btoa(bin);
  }

  document.querySelectorAll('form[data-upload]').forEach((form) => {
    form.addEventListener('submit', async (e) => {
      e.preventDefault();
      const status = form.querySelector('.upload-status');
      const file = form.querySelector('input[type=file]').files[0];
      if (!file) return;
      const maxMb = Number(form.dataset.maxMb || 15);
      if (file.size > maxMb * 1024 * 1024) { status.textContent = `File exceeds ${maxMb} MB.`; return; }
      status.textContent = 'Encrypting and uploading…';
      const fd = new FormData(form);
      try {
        const res = await fetch(form.action, {
          method: 'POST', credentials: 'same-origin',
          headers: { 'content-type': 'application/json', 'x-csrf-token': csrfOf(form) },
          body: JSON.stringify({ name: file.name, folder: fd.get('folder'), classification: fd.get('classification'), documentId: fd.get('documentId') || '', content: toBase64(await file.arrayBuffer()) }),
        });
        const out = await res.json();
        if (!res.ok) { status.textContent = out.error || 'Upload failed.'; return; }
        window.location.href = '/app/dataroom/' + out.id + '?ok=uploaded';
      } catch {
        status.textContent = 'Upload failed. Check your connection and try again.';
      }
    });
  });

  const gf = document.querySelector('form[data-guide]');
  if (gf) {
    gf.addEventListener('submit', async (e) => {
      e.preventDefault();
      const status = gf.querySelector('.upload-status');
      const box = document.getElementById('guide-answer');
      status.textContent = 'Thinking…';
      try {
        const res = await fetch(gf.action, {
          method: 'POST', credentials: 'same-origin',
          headers: { 'content-type': 'application/json', 'x-csrf-token': csrfOf(gf) },
          body: JSON.stringify({ question: new FormData(gf).get('question') }),
        });
        const a = await res.json();
        status.textContent = '';
        box.hidden = false;
        box.replaceChildren();
        if (!res.ok) { box.append(el('p', a.error || 'Something went wrong.', 'form-error')); return; }
        box.append(el('h3', 'Recommended next action'), el('p', a.recommendedNextAction, 'rec'));
        box.append(el('h3', 'Reason'), el('p', a.reason));
        if (a.explanation) box.append(el('h3', 'Explanation'), el('p', a.explanation));
        box.append(el('h3', 'Company facts used'), list(a.companyFactsUsed));
        box.append(el('h3', 'Assumptions or missing facts'), list(a.assumptionsOrMissingFacts));
        box.append(el('h3', 'Sources'), list(a.sources && a.sources.length ? a.sources : ['No registered source cited - verification required.']));
        box.append(el('h3', 'Required reviewer'), el('p', a.requiredReviewer));
        if (a.taskUrl) { const link = el('a', 'Open the related task', 'btn btn-outline btn-sm'); link.href = a.taskUrl; box.append(link); }
        box.append(el('p', a.mode === 'ai' ? 'Generated by an A.I. system - a draft for professional review.' : 'Rule-based guide (no A.I. provider configured).', 'fine'));
      } catch {
        status.textContent = 'The guide is unavailable. Try again shortly.';
      }
    });
  }
  // textContent only - model output is never inserted as HTML.
  function el(tag, text, cls) { const n = document.createElement(tag); n.textContent = text == null ? '' : String(text); if (cls) n.className = cls; return n; }
  function list(items) { const ul = document.createElement('ul'); (items || []).forEach((i) => ul.append(el('li', i))); if (!ul.children.length) ul.append(el('li', 'None')); return ul; }
})();
