// Builds the static edition: a single self-contained index.html (pre-rendered pages, inlined CSS,
// images and demo bundle) plus netlify.toml. Run: npm run build:static
// The static edition has no accounts or stored data; secure features need the server edition.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

process.env.NODE_ENV = 'test'; // render views without touching the dev database or keys
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { landing, securityPage, legalPage } = await import('../src/views/marketing.js');
const A = await import('../src/views/auth.js');
const { brandLockup } = await import('../src/views/layout.js');
const { toHtml } = await import('../src/http.js');

const dataUri = (rel) => `data:image/png;base64,${fs.readFileSync(path.join(ROOT, 'public', rel)).toString('base64')}`;
const images = {}; // each image is embedded once, referenced by key
const LINKS = {
  '/': '#/', '/signup': '#/signup', '/login?demo=1': '#/demo', '/login': '#/login', '/forgot-password': '#/forgot',
  '/security': '#/security', '/legal/terms': '#/terms', '/legal/privacy': '#/privacy', '/app': '#/app',
};
function rewrite(h) {
  return h
    .replace(/href="([^"]*)"/g, (_, u) => {
      const url = u.replace(/&#61;/g, '=');
      if (LINKS[url]) return `href="${LINKS[url]}"`;
      if (url.startsWith('/#')) return `href="#/?s=${url.slice(2)}"`;
      return `href="${u}"`;
    })
    .replace(/src="\/(brand\/[\w.-]+\.png)"/g, (_, p) => { images[p] ??= dataUri(p); return `data-img="${p}"`; });
}
function bodyOf(doc) {
  const s = toHtml(doc);
  const m = /<body class="([^"]*)">([\s\S]*)<\/body>/.exec(s);
  return { cls: m[1], inner: rewrite(m[2].replace(/<a class="skip"[^>]*>[^<]*<\/a>/, '')) };
}
const t = (id, title, doc) => { const b = bodyOf(doc); return `<template id="page-${id}" data-title="${title}" data-body-class="${b.cls}">${b.inner}</template>`; };

const pages = [
  t('landing', 'Your IPO, organized', landing({ nonce: '' })),
  t('security', 'Security', securityPage({ nonce: '' })),
  t('terms', 'Terms of Service', legalPage({ nonce: '', kind: 'terms' })),
  t('privacy', 'Privacy Policy', legalPage({ nonce: '', kind: 'privacy' })),
  t('login', 'Log in', A.loginPage({ nonce: '', csrfToken: '' })),
  t('signup', 'Create your account', A.signupPage({ nonce: '', csrfToken: '' })),
  t('forgot', 'Reset your password', A.forgotPage({ nonce: '', csrfToken: '' })),
  t('demo', 'Live demo', A.demoPage({ nonce: '', csrfToken: '' })),
].join('\n');

const bundle = await build({ entryPoints: [path.join(ROOT, 'src/static/client.js')], bundle: true, format: 'iife', minify: true, platform: 'browser', target: 'es2020', write: false });
const js = bundle.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = fs.readFileSync(path.join(ROOT, 'public/css/site.css'), 'utf8');
const brand = rewrite(toHtml(brandLockup('#/')));

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Thought Authorities A.I. IPO</title>
<meta name="description" content="Thought Authorities A.I. IPO - a guided workspace for Canadian and US IPO readiness, execution and public-company life.">
<link rel="icon" type="image/png" href="${dataUri('favicon.png')}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Cormorant+Garamond:wght@500;600;700&family=Manrope:wght@400;500;600;700&display=swap">
<style>${css}</style>
</head>
<body>
<!-- Static edition, generated by scripts/build-static.js - edit the source files, not this file. -->
<div id="root"><noscript><p style="padding:24px">Please enable JavaScript to view this site.</p></noscript></div>
<template id="tpl-brand">${brand}</template>
<script type="application/json" id="img-data">${JSON.stringify(images)}</script>
${pages}
<script>${js}</script>
</body>
</html>
`;
fs.writeFileSync(path.join(ROOT, 'index.html'), html);

// Netlify: publish only index.html (never the source tree) with strict headers. The CSP allows exactly
// this build's inline script and style by hash.
const scriptHash = crypto.createHash('sha256').update(js).digest('base64');
const styleHash = crypto.createHash('sha256').update(css).digest('base64');
const csp = [
  "default-src 'none'", `script-src 'sha256-${scriptHash}'`, `style-src 'sha256-${styleHash}' https://fonts.googleapis.com`,
  'font-src https://fonts.gstatic.com', 'img-src data:', "form-action 'none'", "frame-ancestors 'none'", "base-uri 'none'", "object-src 'none'",
].join('; ');
fs.writeFileSync(path.join(ROOT, 'netlify.toml'), `# Generated by scripts/build-static.js. Static edition only: no accounts or stored data.
[build]
  command = "mkdir -p dist && cp index.html dist/index.html"
  publish = "dist"

[[headers]]
  for = "/*"
  [headers.values]
    Content-Security-Policy = "${csp}"
    X-Content-Type-Options = "nosniff"
    X-Frame-Options = "DENY"
    Referrer-Policy = "same-origin"
    Permissions-Policy = "camera=(), microphone=(), geolocation=(), payment=()"
    Strict-Transport-Security = "max-age=63072000; includeSubDomains"
`);
console.log(`index.html written (${(html.length / 1024).toFixed(0)} KB) and netlify.toml updated.`);
